-- Create Stored Procedure UPDATESOCIOSPERSONAL
--#SET TERMINATOR @
CREATE PROCEDURE UPDATESOCIOSPERSONAL()
LANGUAGE SQL
P1:
  BEGIN
    COMMIT;
    UPDATE COOPESOCIOS c
    SET (TIPDID, DOCIDE, APEPAT, APEMAT, NOMBRE, DIRECC, LOCALI, PROVIN, DEPART, NCOMPL, NOMBC2, TELCEL, NACION, CCIUDA, NOMCON, DNICY, ESTCIV, CARGAM, OFICIO, SECTO1, FECMODIFICACION) =
        (SELECT 
            CASE WHEN t.TIPDID IS NOT NULL AND t.TIPDID <> '' THEN t.TIPDID ELSE c.TIPDID END,
            CASE WHEN t.DOCIDE IS NOT NULL AND t.DOCIDE <> '' THEN t.DOCIDE ELSE c.DOCIDE END,
            CASE WHEN t.APEPAT IS NOT NULL AND t.APEPAT <> '' THEN t.APEPAT ELSE c.APEPAT END,
            CASE WHEN t.APEMAT IS NOT NULL AND t.APEMAT <> '' THEN t.APEMAT ELSE c.APEMAT END,
            CASE WHEN t.NOMBRE IS NOT NULL AND t.NOMBRE <> '' THEN t.NOMBRE ELSE c.NOMBRE END,
            CASE WHEN t.DIRECC IS NOT NULL AND t.DIRECC <> '' THEN t.DIRECC ELSE c.DIRECC END,
            CASE WHEN t.LOCALI IS NOT NULL AND t.LOCALI <> '' THEN t.LOCALI ELSE c.LOCALI END,
            CASE WHEN t.PROVIN IS NOT NULL AND t.PROVIN <> '' THEN t.PROVIN ELSE c.PROVIN END,
            CASE WHEN t.DEPART IS NOT NULL AND t.DEPART <> '' THEN t.DEPART ELSE c.DEPART END,
            CASE WHEN t.NCOMPL IS NOT NULL AND t.NCOMPL <> '' THEN t.NCOMPL ELSE c.NCOMPL END,
            CASE WHEN t.NOMBC2 IS NOT NULL AND t.NOMBC2 <> '' THEN t.NOMBC2 ELSE c.NOMBC2 END,
            CASE WHEN t.TELCEL IS NOT NULL AND t.TELCEL <> '' THEN t.TELCEL ELSE c.TELCEL END,
            CASE WHEN t.NACION IS NOT NULL AND t.NACION <> '' THEN t.NACION ELSE c.NACION END,
            CASE WHEN t.CCIUDA IS NOT NULL AND t.CCIUDA <> '' THEN t.CCIUDA ELSE c.CCIUDA END,
            CASE WHEN t.NOMCON IS NOT NULL AND t.NOMCON <> '' THEN t.NOMCON ELSE c.NOMCON END,
            CASE WHEN t.DNICY  IS NOT NULL AND t.DNICY  <> '' THEN t.DNICY  ELSE c.DNICY  END,
            CASE WHEN t.ESTCIV IS NOT NULL AND t.ESTCIV <> '' THEN t.ESTCIV ELSE c.ESTCIV END,
            CASE WHEN t.CARGAM IS NOT NULL AND t.CARGAM <> '' THEN t.CARGAM ELSE c.CARGAM END,
            CASE WHEN t.OFICIO IS NOT NULL AND t.OFICIO <> '' THEN t.OFICIO ELSE c.OFICIO END,
            CASE WHEN t.SECTO1 IS NOT NULL AND t.SECTO1 <> '' THEN t.SECTO1 ELSE c.SECTO1 END,
            CURRENT_TIMESTAMP
         FROM COOPESOCIOSTEMPPERSONAL t
         WHERE TRIM(t.DOCUME) = TRIM(c.CODEMPLEADO))
    WHERE EXISTS (
        SELECT 1 
        FROM COOPESOCIOSTEMPPERSONAL t
        WHERE TRIM(t.DOCUME) = TRIM(c.CODEMPLEADO)
    );
    COMMIT;
  END P1@
